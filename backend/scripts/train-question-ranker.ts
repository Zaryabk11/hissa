// Fits the question ranker on SYNTHETIC users and writes src/modules/feel/question-weights.ts.
// Run from backend/: npm run train:questions
import { writeFileSync } from 'node:fs';
import {
  FEATURES,
  buildEvidence,
  features,
  rankQuestions,
  type QuestionWeights,
} from '../src/modules/feel/question-model';
import { GENERATOR_VERSION, generateUser, type SyntheticUser } from './synthetic-question-data';

const TRAIN_SEEDS = [1, 2000] as const;
const HELD_OUT_SEEDS = [100001, 100500] as const; // disjoint from training
const ITERATIONS = 3000;
const LEARNING_RATE = 0.5;

const users = ([from, to]: readonly [number, number]) =>
  Array.from({ length: to - from + 1 }, (_, i) => generateUser(from + i));
const round = (x: number) => Number(x.toFixed(6));
const train = users(TRAIN_SEEDS);
const heldOut = users(HELD_OUT_SEEDS);

// Logistic regression: P(pre_existing is the relevant question) = sigmoid(w.x); symptom_detail scores 0.
const xs = train.map((u) => features(buildEvidence(u.observations)));
const ys = train.map((u) => (u.label === 'pre_existing' ? 1 : 0));
let w = FEATURES.map(() => 0);
for (let it = 0; it < ITERATIONS; it += 1) {
  const grad = FEATURES.map(() => 0);
  xs.forEach((x, i) => {
    const p = 1 / (1 + Math.exp(-x.reduce((s, xk, k) => s + xk * (w[k] ?? 0), 0)));
    x.forEach((xk, k) => (grad[k] = (grad[k] ?? 0) + (p - (ys[i] ?? 0)) * xk));
  });
  w = w.map((wk, k) => wk - (LEARNING_RATE * (grad[k] ?? 0)) / xs.length);
}

const weights: QuestionWeights = {
  symptom_detail: FEATURES.map(() => 0),
  pre_existing: w.map(round),
};
const accuracy = (set: SyntheticUser[], pickTop: (u: SyntheticUser) => string) =>
  round(set.filter((u) => pickTop(u) === u.label).length / set.length);
const baselineAccuracy = accuracy(heldOut, () => 'symptom_detail');
const heldOutAccuracy = accuracy(
  heldOut,
  (u) => rankQuestions(buildEvidence(u.observations), weights)[0] ?? '',
);
const seeds = (r: readonly [number, number]) => `${r[0]}-${r[1]}`;

const file = `// GENERATED by \`npm run train:questions -w backend\` (backend/scripts/train-question-ranker.ts). Do not edit.
// Generator ${GENERATOR_VERSION}; train seeds ${seeds(TRAIN_SEEDS)} (${train.length} users); held-out seeds ${seeds(HELD_OUT_SEEDS)} (${heldOut.length} users).
// Held-out top-question accuracy: fixed baseline (always symptom_detail) ${baselineAccuracy}, trained ranker ${heldOutAccuracy}.
// Features: ${FEATURES.join(', ')}.
// No clinical validity: synthetic data validates question-selection behaviour only, not food or symptom prediction.
import type { QuestionWeights } from './question-model';

export const questionWeights: QuestionWeights = {
  symptom_detail: [${weights.symptom_detail.join(', ')}],
  pre_existing: [${weights.pre_existing.join(', ')}],
};

export const trainingReport = {
  generatorVersion: '${GENERATOR_VERSION}',
  trainSeeds: '${seeds(TRAIN_SEEDS)}',
  heldOutSeeds: '${seeds(HELD_OUT_SEEDS)}',
  trainSize: ${train.length},
  heldOutSize: ${heldOut.length},
  baselineAccuracy: ${baselineAccuracy},
  heldOutAccuracy: ${heldOutAccuracy},
};
`;
writeFileSync('src/modules/feel/question-weights.ts', file);
console.log({ baselineAccuracy, heldOutAccuracy, weights: weights.pre_existing });
