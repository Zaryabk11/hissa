import assert from 'node:assert/strict';
import { test } from 'node:test';
import { parseCatalog, renderSeed } from './build-seed.mjs';

const HEADER =
  'slug,name,category,unit,grams_per_unit,kcal_per_100g,protein_per_100g,carbs_per_100g,fat_per_100g,source,basis,unit_basis';
const ROW = 'daal,Daal,lentil,katori,150,120,7,18,2,khan2019,lab,derived';
const csv = (...rows) => [HEADER, ...rows].join('\n') + '\n';
// Replace one field (by column index) of ROW.
const withField = (i, value) =>
  ROW.split(',')
    .map((f, j) => (j === i ? value : f))
    .join(',');

test('a valid row parses to numbers', () => {
  assert.deepEqual(parseCatalog(csv(ROW)), [
    {
      slug: 'daal',
      name: 'Daal',
      category: 'lentil',
      unit: 'katori',
      grams_per_unit: 150,
      kcal_per_100g: 120,
      protein_per_100g: 7,
      carbs_per_100g: 18,
      fat_per_100g: 2,
      source: 'khan2019',
      basis: 'lab',
      unit_basis: 'derived',
    },
  ]);
});

test('a header-only csv parses to []', () => {
  assert.deepEqual(parseCatalog(csv()), []);
});

const bad = {
  'duplicate slug': [ROW, ROW],
  'bad slug': [ROW, withField(0, 'Bad_Slug')],
  'unknown category': [ROW, withField(2, 'soup')],
  'unknown unit': [ROW, withField(3, 'spoon')],
  'zero grams_per_unit': [ROW, withField(4, '0')],
  'unknown source': [ROW, withField(9, 'wikipedia')],
  'unknown basis': [ROW, withField(10, 'guess')],
  'unknown unit_basis': [ROW, withField(11, 'magic')],
  'name with comma': [ROW, 'x,"Daal, thick",lentil,katori,150,120,7,18,2,khan2019,lab,derived'],
  'name with quote': [ROW, withField(1, 'Dal"x').replace('daal', 'dal-x')],
  'macro mismatch': [ROW, 'x,X,lentil,katori,150,500,7,18,2,khan2019,lab,derived'],
};

for (const [name, rows] of Object.entries(bad)) {
  test(`${name} throws with the row number`, () => {
    assert.throws(
      () => parseCatalog(csv(...rows)),
      (e) => e instanceof Error && e.message.includes('row 3'),
    );
  });
}

test('renderSeed upserts and escapes quotes', () => {
  const rows = parseCatalog(csv(withField(1, "Ma'ash daal")));
  const sql = renderSeed(rows);
  assert.match(sql, /on conflict \(slug\) do update set/);
  assert.ok(sql.includes("'Ma''ash daal'"));
  assert.ok(
    sql.includes(
      'GENERATED by database/scripts/build-seed.mjs from database/data/catalog.csv. Do not edit.',
    ),
  );
});

test('renderSeed([]) has no insert', () => {
  const sql = renderSeed([]);
  assert.doesNotMatch(sql, /insert/i);
  assert.match(sql, /^-- GENERATED/);
});
