import assert from 'node:assert/strict';
import { test } from 'node:test';
import { parseCatalog, renderSeed } from './build-seed.mjs';

const HEADER =
  'slug,name,category,unit,grams_per_unit,kcal_per_100g,protein_per_100g,carbs_per_100g,fat_per_100g,source,basis,unit_basis,protein_type';
const ROW = 'daal,Daal,lentil,katori,150,120,7,18,2,khan2019,lab,derived,';
const csv = (...rows) => [HEADER, ...rows].join('\n') + '\n';
// Replace one field (by column index) of ROW.
const withField = (i, value) =>
  ROW.split(',')
    .map((f, j) => (j === i ? value : f))
    .join(',');

test('a valid row parses to numbers', () => {
  assert.deepEqual(parseCatalog(csv(ROW)), [
    {
      slug: 'daal',
      name: 'Daal',
      category: 'lentil',
      unit: 'katori',
      grams_per_unit: 150,
      kcal_per_100g: 120,
      protein_per_100g: 7,
      carbs_per_100g: 18,
      fat_per_100g: 2,
      source: 'khan2019',
      basis: 'lab',
      unit_basis: 'derived',
      protein_type: null,
    },
  ]);
});

test('a header-only csv parses to []', () => {
  assert.deepEqual(parseCatalog(csv()), []);
});

// A second row with its own slug, so only the field under test is wrong (not "duplicate slug").
const other = (i, value) =>
  withField(0, 'other')
    .split(',')
    .map((f, j) => (j === i ? value : f))
    .join(',');
// [rows, a fragment of the parser's message that tells this failure from the others]
const bad = {
  'duplicate slug': [[ROW, ROW], /duplicate slug "daal"/],
  'bad slug': [[ROW, withField(0, 'Bad_Slug')], /bad slug "Bad_Slug"/],
  'unknown category': [[ROW, other(2, 'soup')], /unknown category "soup"/],
  'unknown unit': [[ROW, other(3, 'spoon')], /unknown unit "spoon"/],
  'zero grams_per_unit': [[ROW, other(4, '0')], /grams_per_unit must be > 0/],
  'unknown source': [[ROW, other(9, 'wikipedia')], /unknown source "wikipedia"/],
  'unknown basis': [[ROW, other(10, 'guess')], /unknown basis "guess"/],
  'unknown unit_basis': [[ROW, other(11, 'magic')], /unknown unit_basis "magic"/],
  'unknown protein_type': [[ROW, other(12, 'pork')], /unknown protein_type "pork"/],
  'name with comma': [
    [ROW, 'other,"Daal, thick",lentil,katori,150,120,7,18,2,khan2019,lab,derived,'],
    /expected 13 columns, got 14/,
  ],
  'name with quote': [[ROW, other(1, 'Dal"x')], /double quote/],
  'macro mismatch': [
    [ROW, 'other,X,lentil,katori,150,500,7,18,2,khan2019,lab,derived,'],
    /kcal 500 does not match macros/,
  ],
};

for (const [name, [rows, fragment]] of Object.entries(bad)) {
  test(`${name} throws with the row number and reason`, () => {
    assert.throws(
      () => parseCatalog(csv(...rows)),
      (e) => e instanceof Error && e.message.includes('row 3') && fragment.test(e.message),
    );
  });
}

test('a leading UTF-8 BOM is ignored', () => {
  assert.equal(parseCatalog('\uFEFF' + csv(ROW)).length, 1);
});

test('renderSeed upserts and escapes quotes', () => {
  const rows = parseCatalog(csv(withField(1, "Ma'ash daal")));
  const sql = renderSeed(rows);
  assert.match(sql, /on conflict \(slug\) do update set/);
  assert.ok(sql.includes("'Ma''ash daal'"));
  assert.match(sql, /rows removed from the CSV are NOT deleted/i);
  assert.ok(
    sql.includes(
      'GENERATED by database/scripts/build-seed.mjs from database/data/catalog.csv. Do not edit.',
    ),
  );
});

test('renderSeed([]) has no insert', () => {
  const sql = renderSeed([]);
  assert.doesNotMatch(sql, /insert/i);
  assert.match(sql, /^-- GENERATED/);
});

test('parseCatalog accepts an empty protein_type as null and a known one as is', () => {
  assert.equal(parseCatalog(csv(ROW))[0].protein_type, null);
  assert.equal(parseCatalog(csv(withField(12, 'veg')))[0].protein_type, 'veg');
});

test('seed sql includes protein_type, null for empty', () => {
  const sql = renderSeed(parseCatalog(csv(ROW, other(12, 'beef'))));
  assert.match(sql, /unit_basis, protein_type\)/);
  assert.match(sql, /'derived', null\)/);
  assert.match(sql, /'derived', 'beef'\)/);
  assert.match(sql, /protein_type = excluded\.protein_type/);
});
