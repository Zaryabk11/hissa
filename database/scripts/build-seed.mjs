// Turns database/data/catalog.csv into database/supabase/seed.sql.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const COLUMNS = [
  'slug',
  'name',
  'category',
  'unit',
  'grams_per_unit',
  'kcal_per_100g',
  'protein_per_100g',
  'carbs_per_100g',
  'fat_per_100g',
  'source',
  'basis',
  'unit_basis',
  'protein_type',
];
const NUMERIC = [
  'grams_per_unit',
  'kcal_per_100g',
  'protein_per_100g',
  'carbs_per_100g',
  'fat_per_100g',
];
const ENUMS = {
  category: ['rice', 'roti', 'fried', 'lentil', 'meat', 'sweets', 'other'],
  unit: ['roti', 'katori', 'plate', 'piece', 'glass', 'bowl'],
  source: ['khan2019', 'farooq2026', 'indb'],
  basis: ['lab', 'calculated'],
  unit_basis: ['derived', 'assumed'],
};
const PROTEIN_TYPES = ['beef', 'mutton', 'chicken', 'fish', 'egg', 'veg'];

// Row numbers are file line numbers (header is row 1), so errors point at the line to fix.
export function parseCatalog(csvText) {
  const lines = csvText.split(/\r?\n/);
  // trim() also strips a leading UTF-8 BOM.
  if (lines[0].trim() !== COLUMNS.join(','))
    throw new Error(`row 1: header must be ${COLUMNS.join(',')}`);
  const seen = new Set();
  const rows = [];
  lines.forEach((line, i) => {
    if (i === 0 || line.trim() === '') return;
    const fail = (msg) => {
      throw new Error(`row ${i + 1}: ${msg}`);
    };
    const cells = line.split(',').map((c) => c.trim());
    if (cells.length !== COLUMNS.length)
      fail(
        `expected ${COLUMNS.length} columns, got ${cells.length} (names may not contain commas)`,
      );
    const row = Object.fromEntries(COLUMNS.map((c, j) => [c, cells[j]]));

    if (!/^[a-z0-9-]+$/.test(row.slug)) fail(`bad slug "${row.slug}"`);
    if (seen.has(row.slug)) fail(`duplicate slug "${row.slug}"`);
    seen.add(row.slug);
    if (!row.name || row.name.includes('"'))
      fail('name must be non-empty and contain no double quote');
    for (const [col, allowed] of Object.entries(ENUMS)) {
      if (!allowed.includes(row[col])) fail(`unknown ${col} "${row[col]}"`);
    }
    // Empty protein_type means no avoid-by-protein group for this dish.
    if (row.protein_type === '') row.protein_type = null;
    else if (!PROTEIN_TYPES.includes(row.protein_type))
      fail(`unknown protein_type "${row.protein_type}"`);
    for (const col of NUMERIC) {
      const n = Number(row[col]);
      if (row[col] === '' || !Number.isFinite(n)) fail(`${col} is not a number`);
      row[col] = n;
    }
    if (row.grams_per_unit <= 0) fail('grams_per_unit must be > 0');
    if (row.kcal_per_100g <= 0) fail('kcal_per_100g must be > 0');
    if (row.protein_per_100g < 0 || row.carbs_per_100g < 0 || row.fat_per_100g < 0)
      fail('macros must be >= 0');
    const atwater = 4 * row.protein_per_100g + 4 * row.carbs_per_100g + 9 * row.fat_per_100g;
    if (Math.abs(row.kcal_per_100g - atwater) > 0.25 * row.kcal_per_100g + 15) {
      fail(`kcal ${row.kcal_per_100g} does not match macros (4p+4c+9f = ${atwater})`);
    }
    rows.push(row);
  });
  return rows;
}

const sql = (v) =>
  v === null ? 'null' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`;

export function renderSeed(rows, recipes = []) {
  const header =
    '-- GENERATED by database/scripts/build-seed.mjs from database/data/catalog.csv. Do not edit.\n' +
    '-- Upsert only: rows removed from the CSV are NOT deleted from an existing database.\n';
  if (rows.length === 0) return header;
  const slugs = new Set(rows.map((r) => r.slug));
  for (const r of recipes)
    if (!slugs.has(r.dish)) throw new Error(`recipe "${r.slug}": unknown dish "${r.dish}"`);
  const values = rows.map((r) => `  (${COLUMNS.map((c) => sql(r[c])).join(', ')})`).join(',\n');
  const updates = COLUMNS.filter((c) => c !== 'slug')
    .map((c) => `${c} = excluded.${c}`)
    .join(', ');
  const dishes = `insert into public.dishes (${COLUMNS.join(', ')}) values\n${values}\non conflict (slug) do update set ${updates};\n`;
  return header + dishes + renderRecipes(recipes);
}

function renderRecipes(recipes) {
  if (recipes.length === 0) return '';
  const values = recipes
    .map(
      (r) =>
        `  (${sql(r.slug)}, ${sql(r.title)}, (select id from public.dishes where slug = ${sql(r.dish)}), ${r.minutes}, ${r.servings}, ${sql(JSON.stringify(r.ingredients))}::jsonb, ${sql(JSON.stringify(r.steps))}::jsonb, ${r.reviewed ? 'true' : 'false'})`,
    )
    .join(',\n');
  return `insert into public.recipes (slug, title, dish_id, minutes, servings, ingredients, steps, reviewed) values\n${values}\non conflict (slug) do update set title = excluded.title, dish_id = excluded.dish_id, minutes = excluded.minutes, servings = excluded.servings, ingredients = excluded.ingredients, steps = excluded.steps, reviewed = excluded.reviewed;\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const read = (p) => readFileSync(fileURLToPath(new URL(p, import.meta.url)), 'utf8');
  const recipes = JSON.parse(read('../data/recipes.json'));
  const seed = renderSeed(parseCatalog(read('../data/catalog.csv')), recipes);
  writeFileSync(fileURLToPath(new URL('../supabase/seed.sql', import.meta.url)), seed);
}
